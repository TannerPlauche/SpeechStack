// Generates src/data/wordlists.generated.ts from data/source/wordlists.json.
// Metro can only bundle images referenced by literal require() calls, so the
// image map has to be written out as code. Re-run after adding new flashcards:
//   npm run build:wordlists
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(join(root, 'data/source/wordlists.json'), 'utf8'));
const outFile = join(root, 'src/data/wordlists.generated.ts');

const sounds = [];
const words = [];
let withImages = 0;

for (const [soundId, sound] of Object.entries(source.sounds)) {
  sounds.push({ id: soundId, label: sound.label, phonemes: sound.phonemes, notes: sound.notes ?? null });
  for (const [position, entries] of Object.entries(sound.positions)) {
    for (const e of entries) {
      // Card files live in assets/flashcards/ (the package's flashcards/ folder).
      const fileName = e.flashcard_file?.replace(/^flashcards\//, '');
      const hasImage = e.flashcard_status === 'ready' && fileName && existsSync(join(root, 'assets/flashcards', fileName));
      if (hasImage) withImages++;
      words.push({
        id: e.id,
        sound: soundId,
        position,
        word: e.word,
        ipa: e.ipa,
        targetIpa: e.target_ipa,
        variant: e.target_variant ?? null,
        cue: e.image_cue ?? null,
        targetSpan: e.flashcard_target_text_span ? [e.flashcard_target_text_span.start, e.flashcard_target_text_span.end] : null,
        image: hasImage ? fileName : null,
      });
    }
  }
}

const wordLines = words.map(({ image, ...w }) => {
  const json = JSON.stringify(w);
  const img = image ? `require('../../assets/flashcards/${image}')` : 'null';
  return `  { ...${json}, image: ${img} },`;
});

const out = `// AUTO-GENERATED by scripts/build-wordlists.mjs — do not edit by hand.
// Source: data/source/wordlists.json (schema ${source.schema_version}, ${source.dialect})
import type { SoundInfo, WordEntry } from './types';

export const SOUNDS: SoundInfo[] = ${JSON.stringify(sounds, null, 2)};

export const WORDS: WordEntry[] = [
${wordLines.join('\n')}
];
`;

writeFileSync(outFile, out);
console.log(`Wrote ${words.length} words (${withImages} with pictures) across ${sounds.length} sounds to ${outFile}`);
